function randomElement<T>(arr: T[]): T {
	return arr[Math.floor(Math.random() * arr.length)];
}

enum Pool {
	Simple,
	Kao,
	Ascii,
	Rare,
}

export class Meowdule {
	private readonly bot_user_id: string;
	constructor(client: SapphireClient<true>) {
		this.bot_user_id = client.user.id;
	}

	private randomPool(): Pool {
		const r = Math.random();
		if (r <= 0.49) return Pool.Simple;
		else if (r <= 0.84) return Pool.Kao;
		else if (r <= 0.99) return Pool.Ascii;
		else return Pool.Rare;
	}

	handleMsg(msg: Message<true>) {
		if (!msg.mentions.has(this.bot_user_id)) return;
		if (msg.author.id === this.bot_user_id) return;

		const pool: Pool = this.randomPool();

		let msg_options: string | MessagePayload | MessageReplyOptions;

		switch (pool) {
			case Pool.Simple: {
				msg_options = {
					content: randomElement(simple),
				};
				break;
			}
			case Pool.Ascii: {
				msg_options = {
					content: randomElement(ascii),
				};
				break;
			}
			case Pool.Kao: {
				msg_options = {
					content: randomElement(kao),
				};
				break;
			}
			case Pool.Rare: {
				msg_options = {
					content: randomElement(rare),
				};
				break;
			}
		}
		if (msg_options.content?.charAt(0) === ' ') {
			msg_options.content = '‎' + msg_options.content.slice(1);
		}
		msg.reply(msg_options);
	}
}
